const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8768/',{waitUntil:'networkidle'});
 assert.match(await page.locator('#historical-status').innerText(),/按下按鈕/);
 await page.locator('#historical-run').click();
 assert.equal(await page.locator('#historical-symbol').isDisabled(),true);
 await page.waitForFunction(()=>document.querySelectorAll('#historical-summary tr').length===4,{},{timeout:120000});
 assert.match(await page.locator('#historical-status').innerText(),/2303.TW/);
 assert.match(await page.locator('#historical-status').innerText(),/2026-10-02/);
 await page.locator('#historical-backtest details summary').click();
 assert.ok(await page.locator('#historical-records tr').count()>50);
 assert.match(await page.locator('#historical-records').innerText(),/缺少該日收盤/);
 await page.locator('#historical-backtest').screenshot({path:'/workspace/StockPredict-fresh/artifacts/historical-zh.png'});
 await page.selectOption('#language-select','en');
 assert.match(await page.locator('#historical-title').innerText(),/Historical backtest/);
 assert.match(await page.locator('#historical-head').innerText(),/baseline MAE/);
 assert.match(await page.locator('#historical-records').innerText(),/Session close missing/);
 await page.selectOption('#historical-symbol','2330.TW');
 assert.equal(await page.locator('#historical-summary tr').count(),0);
 await page.locator('#historical-run').click();
 await page.waitForFunction(()=>document.querySelectorAll('#historical-summary tr').length===4,{},{timeout:120000});
 assert.match(await page.locator('#historical-status').innerText(),/2330.TW/);
 await page.locator('#historical-backtest details summary').click();
 await page.locator('#historical-backtest').screenshot({path:'/workspace/StockPredict-fresh/artifacts/historical-en.png'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.locator('#historical-backtest').screenshot({path:'/workspace/StockPredict-fresh/artifacts/historical-mobile.png'});
 await page.route('**/api/historical-backtest*',route=>route.fulfill({status:502,contentType:'application/json',body:'{"status":"unavailable","reason":"data_unavailable"}'}));
 await page.locator('#historical-run').click();
 await page.waitForFunction(()=>!document.getElementById('historical-run').disabled);
 assert.match(await page.locator('#historical-status').innerText(),/unavailable/);
 assert.equal(await page.locator('#historical-summary tr').count(),0);
 assert.deepEqual(errors,[]);
 fs.writeFileSync('/workspace/StockPredict-fresh/artifacts/historical-browser.json',JSON.stringify({passed:true,checks:['live UMC walk-forward API','live TSMC walk-forward API','zh-TW/en','1/5 day horizons and separate ADR groups','missing actual labels','selection clears old results','loading lock','390px mobile','upstream failure handling'],pageErrors:errors},null,2));
 await browser.close(); console.log('Historical browser checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
